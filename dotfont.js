const R = 0.45; // 点の半径（1マス＝1）

// text をドット文字の <svg> にして返す。height は px（10以上にする）。
// label は読み上げ用の文字（省略すると text）。
export function dotText(text, height = 14, label = text) {
  const chars = [...String(text).toUpperCase().replace(/—/g, '-')];
  let d = '';
  chars.forEach((ch, i) => {
    const rows = (G[ch] ?? G[' ']).split(',');
    rows.forEach((row, y) => {
      for (let x = 0; x < 5; x++) {
        if (row[x] !== '1') continue;
        const cx = i * 6 + x + 0.5;
        const cy = y + 0.5;
        d += `M${cx - R} ${cy}a${R} ${R} 0 1 0 ${2 * R} 0a${R} ${R} 0 1 0 ${-2 * R} 0`;
      }
    });
  });
  const cols = Math.max(chars.length * 6 - 1, 1);
  const unit = height / 7;
  const safe = String(label).replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);
  return `<svg class="dot" viewBox="0 0 ${cols} 7" width="${(cols * unit).toFixed(1)}" height="${height}" role="img" aria-label="${safe}" fill="currentColor"><path d="${d}"/></svg>`;
}
